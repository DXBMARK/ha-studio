#!/usr/bin/env python3
"""Turn a design-token file (assets/tokens/<name>.json) into a Home Assistant theme YAML.

  gen_theme.py aurora [--out themes/dxbmark_aurora.yaml]

Dark tokens become `modes.dark`; the light "frost" token set becomes `modes.light`.  Put the file in
<config>/themes/ (with `frontend: themes: !include_dir_merge_named themes` in configuration.yaml), then
call the `frontend.reload_themes` action.  Variable names follow the public HA theming documentation;
`ha-card-backdrop-filter` is only honoured by recent HA versions — older ones ignore it (cards stay readable).
"""
import argparse, json, pathlib, sys
from _common import ROOT, dump_yaml, die, write_text
from contrast_check import parse, over

def solid(tok):
    r, g, b, _ = over(parse(tok['colors']['card']), parse(tok['base']))
    return '#%02x%02x%02x' % (round(r), round(g), round(b))


def theme_vars(tok):
    c, v = tok['colors'], tok['cssVars']
    return {
        'primary-color': c['acc'],
        'accent-color': c['acc'],
        'primary-text-color': c['t'],
        'secondary-text-color': c['m'],
        'text-primary-color': c['ona'],
        'primary-background-color': tok['base'],
        'secondary-background-color': tok['base'],
        # card-background-color is kept opaque; only ha-card uses the translucent glass value
        'card-background-color': solid(tok),
        'ha-card-background': c['card'],
        'ha-card-border-radius': v['--r'],
        'ha-card-border-width': '1px',
        'ha-card-border-color': c['border'],
        'ha-card-box-shadow': c['shadow'],
        'ha-card-backdrop-filter': v['--blur'],
        'divider-color': c['line'],
        'state-icon-color': c['acct'],
        'success-color': c['ok'],
        'warning-color': c['warn'],
        'error-color': c['bad'],
        'app-header-background-color': tok['base'],
    }

def build(tok):
    light = tok['slug'] == 'frost'
    name = f'dxbmark_{tok["slug"]}'
    return {name: {'modes': {('light' if light else 'dark'): theme_vars(tok)}}}

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('name'); ap.add_argument('--out'); ap.add_argument('--force', action='store_true')
    a = ap.parse_args()
    f = ROOT / 'assets' / 'tokens' / f'{a.name}.json'
    if not f.exists():
        die(f'unknown token set: {a.name}')
    tok = json.loads(f.read_text())
    text = dump_yaml(build(tok), '# HA theme generated by ha-studio (DXBMARK LLC, Apache-2.0)')
    if a.out:
        write_text(a.out, text, a.force)
        print(f'→ {a.out}', file=sys.stderr)
    else:
        print(text)

if __name__ == '__main__':
    main()
